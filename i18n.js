const DICT = { en: EN, ru: RU };

function normalizeLang(value) {
  const v = String(value || "").trim().toLowerCase().slice(0, 2);
  return LANGS.includes(v) ? v : DEFAULT_LANG;
}

/** `{name}` placeholders; a missing key falls back to English, then to the key itself. */
function t(lang, key, vars) {
  const table = DICT[normalizeLang(lang)] || EN;
  let out = table[key];
  if (out === undefined) out = EN[key];
  if (out === undefined) return key;
  if (!vars) return out;
  return out.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole
  );
}

module.exports = { DICT, LANGS, DEFAULT_LANG, EN, RU, normalizeLang, t };
